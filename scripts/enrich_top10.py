def load_base(base_id: str) -> dict:
    path = BASE_DIR / f"{base_id}.json"
    with open(path) as f:
        return json.load(f)


def write_base(data: dict) -> None:
    path = BASE_DIR / f"{data['id']}.json"
    data["dataUpdatedAt"] = NOW
    with open(path, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Wrote {path.name}  ({len(data['resources'])} resources)")


def add_resources_if_missing(base: dict, extras: list[dict]) -> None:
    """Add resources that don't already have the same id."""
    existing_ids = {r["id"] for r in base["resources"]}
    added = 0
    for r in extras:
        if r["id"] not in existing_ids:
            base["resources"].append(r)
            added += 1
    print(f"  → added {added} new resources to {base['id']}")


